namespace Content.Client._Goobstation.Silicon.AiCameraWarping.Ui; // Goobstation

[GenerateTypedNameReferences]
public sealed partial class AiCameraWarpMenu : FancyWindow
{
    // QB edit start - camera map
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private static readonly Color CameraBlipColor = Color.FromHex("#FF00FF");
    private readonly Texture _cameraBlipTexture;

    /// <summary>
    /// The cameras the list was last built from, so it is only rebuilt (losing scroll position) when it changes.
    /// </summary>
    private List<(NetEntity Camera, string Name)> _listed = new();
    // QB edit end

    public event Action<CameraWarpActionEvent>? OnCamWarpAction;
    public event Action? OnRefresh;

    public AiCameraWarpMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this); // QB

        SearchBar.OnTextChanged += _ => UpdateVisibleButtons();
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();

        // QB edit start - clicking a camera blip on the map jumps to that camera
        _cameraBlipTexture = _resourceCache.GetTexture("/Textures/Interface/NavMap/beveled_triangle.png");

        NavMap.TrackedEntitySelectedAction += camera =>
        {
            if (camera != null)
                OnCamWarpAction?.Invoke(new CameraWarpActionEvent(camera.Value));
        };
        // QB edit end
    }

    // QB edit start - camera map
    /// <summary>
    /// Sets the grid the map draws. Cameras are only ever listed for the AI core's own grid.
    /// </summary>
    public void SetGrid(EntityUid? grid)
    {
        NavMap.MapUid = grid;
        NavMap.Visible = grid != null;
        NavMap.ForceNavMapUpdate();
    }
    // QB edit end

    public void Update(CameraWarpBuiState state)
    {
        if (state.CameraList == null)
            return;

        // QB edit start - the map is redrawn on every update, since cameras can move
        NavMap.TrackedEntities.Clear();

        foreach (var data in state.CameraList)
        {
            var coordinates = _entManager.GetCoordinates(data.Coordinates);
            if (!coordinates.IsValid(_entManager))
                continue;

            NavMap.TrackedEntities[data.NetEntityUid] = new NavMapBlip(coordinates, _cameraBlipTexture, CameraBlipColor, false);
        }

        // Sort the list alphabetically, with a stable order for cameras that share a name
        state.CameraList.Sort((a, b) =>
        {
            var byName = string.Compare(a.DisplayName, b.DisplayName, StringComparison.CurrentCulture);
            return byName != 0 ? byName : a.NetEntityUid.Id.CompareTo(b.NetEntityUid.Id);
        });

        var listed = state.CameraList.Select(data => (data.NetEntityUid, data.DisplayName)).ToList();
        if (listed.SequenceEqual(_listed))
            return;

        _listed = listed;
        // QB edit end

        CameraWarpsDisplayContainer.Children.Clear();

        var previousName = "";
        var i = 2;

        state.CameraList.ForEach(data =>
        {
            // This is to make the menu more readable when
            // there is many duplicate names.
            if (data.DisplayName.Equals(previousName))
            {
                data.DisplayName = $"{previousName} {i++}";
            }
            else
            {
                previousName = data.DisplayName;
                i = 2;
            }

            var button = new Button
            {
                Text = data.DisplayName
            };

            button.OnPressed += _ =>
            {
                OnCamWarpAction?.Invoke(new CameraWarpActionEvent(data.NetEntityUid));
            };

            CameraWarpsDisplayContainer.AddChild(button);
        });

        UpdateVisibleButtons(); // QB - keep the search filter applied after a rebuild
    }

    private void UpdateVisibleButtons()
    {
        foreach (var child in CameraWarpsDisplayContainer.Children)
        {
            if (child is Button button)
                button.Visible = button.Text != null && button.Text.Contains(SearchBar.Text, StringComparison.CurrentCultureIgnoreCase);
        }
    }
}
